// Records every sentence the games say in each voice, as small MP3s in public/voice/<voice>/,
// and lists the recorded sentences in src/lib/voice-manifest.ts.
// Sentences already recorded are skipped, so re-running only records new lines.
//   npm install && npm run generate             (records what is missing)
//   npm run generate -- --redo                  (records everything again, e.g. after changing a voice)
import fs from "node:fs";
import path from "node:path";
import { Mp3Encoder } from "@breezystack/lamejs";
import { KokoroTTS } from "kokoro-js";
import { allSentences, appRoot, spokenForm } from "./phrases.mjs";

/** The Kokoro voice behind each choice in the grown-up settings. */
const voices = { female: "af_heart", male: "am_michael" };
/** A little slower than normal for young listeners. */
const SPEED = 0.9;
const BITRATE = 48;

const redo = process.argv.includes("--redo");
const sentences = allSentences();
const tts = await KokoroTTS.from_pretrained("onnx-community/Kokoro-82M-v1.0-ONNX", { dtype: "q8", device: "cpu" });

function encodeMp3(samples, sampleRate) {
  const pcm = Int16Array.from(samples, (value) => Math.max(-32768, Math.min(32767, Math.round(value * 32767))));
  const encoder = new Mp3Encoder(1, sampleRate, BITRATE);
  const chunks = [];
  for (let start = 0; start < pcm.length; start += 1152) chunks.push(encoder.encodeBuffer(pcm.subarray(start, start + 1152)));
  chunks.push(encoder.flush());
  return Buffer.concat(chunks.map((chunk) => Buffer.from(chunk.buffer, chunk.byteOffset, chunk.length)));
}

/** Trims the model's leading and trailing near-silence (keeping a short natural pause). */
function trimSilence(samples, sampleRate) {
  const threshold = 0.01;
  const pad = Math.round(sampleRate * 0.06);
  let start = samples.findIndex((value) => Math.abs(value) > threshold);
  let end = samples.findLastIndex((value) => Math.abs(value) > threshold);
  if (start < 0) return samples;
  start = Math.max(0, start - pad);
  end = Math.min(samples.length, end + pad);
  return samples.subarray(start, end);
}

for (const [gender, voice] of Object.entries(voices)) {
  const folder = path.join(appRoot, "public", "voice", gender);
  fs.mkdirSync(folder, { recursive: true });
  let made = 0;
  for (const [key, sentence] of sentences) {
    const file = path.join(folder, `${key}.mp3`);
    if (!redo && fs.existsSync(file)) continue;
    const audio = await tts.generate(spokenForm(sentence), { voice, speed: SPEED });
    fs.writeFileSync(file, encodeMp3(trimSilence(audio.audio, audio.sampling_rate), audio.sampling_rate));
    made++;
    if (made % 25 === 0) console.log(`${gender}: ${made} recorded…`);
  }
  // Recordings for sentences the games no longer say.
  for (const name of fs.readdirSync(folder)) if (name.endsWith(".mp3") && !sentences.has(name.slice(0, -4))) fs.rmSync(path.join(folder, name));
  console.log(`${gender} (${voice}): ${made} new, ${sentences.size} in all`);
}

// Only sentences recorded in every voice are listed, so switching voices never mixes voices in a line.
const everywhere = [...sentences.keys()].filter((key) => Object.keys(voices).every((gender) => fs.existsSync(path.join(appRoot, "public", "voice", gender, `${key}.mp3`)))).sort();
fs.writeFileSync(path.join(appRoot, "src", "lib", "voice-manifest.ts"), `// Generated by scripts/voice/generate.mjs: the sentences recorded in every voice. Do not edit.\nexport const voiceClipKeys = "${everywhere.join(" ")}";\n`);
console.log(`Manifest: ${everywhere.length} sentences.`);
